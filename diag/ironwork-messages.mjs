// Write rules/ironwork-messages.json from ironwork's docs/messages.md: every message id with its
// area, severity and text, and a remedy for every W and E message and every X message. Remedies
// already in the file are kept as written; an id that needs one and has none gets its area's default.
//
// Usage: node diag/ironwork-messages.mjs [messages.md] [--commit <sha>] [--out <json>]
//   With no file, IRONWORK_MESSAGES names one; without that, docs/messages.md is read from the
//   ironwork checkout (IRONWORK_CHECKOUT, default ../ironwork beside this repository) at origin/main.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = 'https://github.com/Portll/ironwork';
const DOC = 'docs/messages.md';
const REF = 'origin/main';

const args = process.argv.slice(2);
const flag = (name) => { const i = args.indexOf(name); if (i < 0) return null; const v = args[i + 1]; args.splice(i, 2); return v; };
const commitGiven = flag('--commit');
const out = resolve(flag('--out') || resolve(HERE, '..', 'rules', 'ironwork-messages.json'));
const file = args[0] || process.env.IRONWORK_MESSAGES || null;

let text, commit;
if (file) {
  text = readFileSync(file, 'utf8');
  commit = commitGiven;
} else {
  const checkout = resolve(process.env.IRONWORK_CHECKOUT || resolve(HERE, '..', '..', 'ironwork'));
  text = execFileSync('git', ['-C', checkout, 'show', `${REF}:${DOC}`], { encoding: 'utf8' });
  commit = commitGiven || execFileSync('git', ['-C', checkout, 'log', '-1', '--format=%H', REF, '--', DOC], { encoding: 'utf8' }).trim();
}

const ROW = /^\| (IW([A-Z])\d{4}) \| ([IWESU]) \| `(.*)` \|$/;
const messages = [];
for (const line of text.split(/\r?\n/)) {
  if (!line.startsWith('| IW')) continue;
  const m = ROW.exec(line);
  if (!m) throw new Error(`a message row this reader does not know: ${line}`);
  messages.push({ id: m[1], area: m[2], severity: m[3], text: m[4] });
}
if (!messages.length) throw new Error(`no message rows in ${file || DOC}`);
const ids = new Set(messages.map((m) => m.id));
if (ids.size !== messages.length) throw new Error('an id is listed twice');
messages.sort((a, b) => a.id.localeCompare(b.id));

const needsRemedy = (m) => m.area === 'X' || m.severity === 'W' || m.severity === 'E';

const before = existsSync(out) ? JSON.parse(readFileSync(out, 'utf8')) : {};
const defaults = before.defaultRemedies || {};
const remedies = { ...(before.remedies || {}) };
const lacking = [];
for (const m of messages.filter(needsRemedy)) {
  if (typeof remedies[m.id] === 'string') continue;
  if (defaults[m.area]) remedies[m.id] = defaults[m.area];
  else lacking.push(m.id);
}
if (lacking.length) throw new Error(`no remedy and no default for area ${[...new Set(lacking.map((id) => id[2]))].join(', ')}: ${lacking.join(', ')}`);

const tally = (key) => Object.fromEntries(Object.entries(messages.reduce((o, m) => ({ ...o, [m[key]]: (o[m[key]] || 0) + 1 }), {})).sort(([a], [b]) => a.localeCompare(b)));
const same = before.source && before.source.commit === commit && JSON.stringify(before.messages) === JSON.stringify(messages);
const doc = {
  _comment: 'ironwork\'s compiler messages by id, as docs/messages.md lists them, with the remedy cobolwork gives each W, E and X message. GENERATED by diag/ironwork-messages.mjs: messages and source are rewritten on each run; remedies and defaultRemedies are written by hand and kept.',
  schemaVersion: 1,
  source: { repo: REPO, path: DOC, commit: commit || null, retrieved: same ? before.source.retrieved : new Date().toISOString().slice(0, 10) },
  counts: { messages: messages.length, bySeverity: tally('severity'), byArea: tally('area') },
  defaultRemedies: defaults,
  remedies: Object.fromEntries(Object.entries(remedies).sort(([a], [b]) => a.localeCompare(b))),
  messages,
};
writeFileSync(out, `${JSON.stringify(doc, null, 2)}\n`);
console.log(`wrote ${out}: ${messages.length} messages (${Object.entries(doc.counts.bySeverity).map(([k, v]) => `${v} ${k}`).join(', ')}), ${Object.keys(doc.remedies).length} remedies`);
