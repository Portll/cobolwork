// Write test/fixtures/evidence/kinds.tsv from lib/evidence/record.mjs: each record kind, the file it
// belongs in, the fields it may carry and those it must. ironwork vendors the table and holds the
// records its run journal writes to it, so neither tool writes a record the other's verifier refuses.
//
// Usage: node generate-evidence-kinds.mjs <destTsv>
import { writeFileSync } from 'node:fs';
import { JOURNAL_KINDS, KINDS, LEDGER_KINDS } from '../lib/evidence/record.mjs';

const [dest] = process.argv.slice(2);
if (!dest) { console.error('usage: generate-evidence-kinds.mjs <destTsv>'); process.exit(2); }

const rows = Object.entries(KINDS).map(([kind, spec]) => {
  const file = JOURNAL_KINDS.has(kind) ? 'journal' : LEDGER_KINDS.has(kind) ? 'ledger' : null;
  if (!file) { console.error(`${kind} is in neither JOURNAL_KINDS nor LEDGER_KINDS`); process.exit(3); }
  return [kind, file, Object.keys(spec.fields).join(' '), spec.required.join(' ')].join('\t');
});

writeFileSync(dest, [
  '# Generated by diag/generate-evidence-kinds.mjs from lib/evidence/record.mjs; do not edit.',
  '# kind\tfile\tfields\trequired',
  ...rows,
  '',
].join('\n'));
