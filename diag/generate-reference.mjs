// Write the reference pages under docs/reference/ from `cobolwork capabilities` and nothing else.
//
// Usage: node diag/generate-reference.mjs [destDir]
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { capabilities } from '../lib/capabilities.mjs';

const MARK = 'This page is generated by `node diag/generate-reference.mjs` from `cobolwork capabilities`. Change the facts there, not this page.';

const cell = (s) => String(s).replace(/\|/g, '\\|');
const table = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');
const code = (s) => `\`${s}\``;
// An option's text for one command: its own wording if it has one, else the summary without a leading "<command>: ".
const sentence = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const summaryFor = (o, command) => sentence((o.commands && o.commands[command]) || o.summary.replace(new RegExp(`^${command}( [a-z]+)*: `), ''));
const optionCell = (name, o) => code(o && o.value ? `${name} <${o.value}>` : name);

function commandPage(name, c, caps) {
  const usage = ['cobolwork', name, ...c.args, ...(c.options.length ? ['[options]'] : [])].join(' ');
  const out = [`# cobolwork ${name}`, '', MARK, '', c.summary, '', '## Usage', '', '```', usage, '```', ''];
  out.push('## Options', '');
  const own = c.options.map((o) => [optionCell(o, caps.options[o]), summaryFor(caps.options[o], name)]);
  out.push(own.length ? table(['Option', 'What it does'], own) : 'This command takes no options of its own.', '');
  out.push('Every command also takes ' + caps.globalOptions.map(code).join(', ') + '.', '');
  out.push('## Exit statuses', '', table(['Status', 'Meaning'], [...c.exit].sort((a, b) => a.status - b.status).map((e) => [e.status, e.meaning])), '');
  out.push('## Documents written', '', c.documents.length ? c.documents.map((d) => `- ${code(d)}, version ${caps.documents[d]}`).join('\n') : 'None. This command is interactive.', '');
  out.push('[Back to the reference index](README.md)', '');
  return out.join('\n');
}

function indexPage(caps) {
  const rows = Object.entries(caps.commands).map(([n, c]) => [`[${code('cobolwork ' + n)}](${n}.md)`, c.summary]);
  return [
    '# cobolwork reference', '', MARK, '',
    '## Commands', '', table(['Command', 'What it does'], rows), '',
    '## Other pages', '',
    '- [Environment variables](environment.md)',
    '- [Site file keys](site-file.md)', '',
    '## Exit statuses', '',
    'cobolwork and ironwork give each status one meaning.', '',
    table(['Status', 'Meaning'], caps.exitStatuses.map((e) => [e.status, e.meaning])), '',
    '## Options every command takes', '',
    table(['Option', 'What it does'], caps.globalOptions.map((o) => [optionCell(o, caps.options[o]), summaryFor(caps.options[o], '')])), '',
  ].join('\n');
}

function environmentPage(caps) {
  return [
    '# Environment variables', '', MARK, '',
    'A variable that names files takes a list of paths separated by the platform\'s path delimiter.', '',
    table(['Variable', 'Value', 'What it does'], caps.environment.map((e) => [code(e.name), e.value, e.summary])), '',
    '[Back to the reference index](README.md)', '',
  ].join('\n');
}

function sitePage(caps) {
  const s = caps.siteFile;
  return [
    `# Site file keys`, '', MARK, '',
    `${code(s.file)} holds the facts about an estate that no repository holds. It is read from the root of the scanned tree. Its version is ${s.version}. A key opening with an underscore is a note for people.`, '',
    table(['Key', 'Type', 'What it holds'], s.keys.map((k) => [code(k.key), k.type, k.summary])), '',
    '[Back to the reference index](README.md)', '',
  ].join('\n');
}

export function renderReference(caps = capabilities()) {
  const pages = new Map([['README.md', indexPage(caps)], ['environment.md', environmentPage(caps)], ['site-file.md', sitePage(caps)]]);
  for (const [name, c] of Object.entries(caps.commands)) pages.set(`${name}.md`, commandPage(name, c, caps));
  return pages;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const dest = process.argv[2] || fileURLToPath(new URL('../docs/reference/', import.meta.url));
  mkdirSync(dest, { recursive: true });
  const pages = renderReference();
  for (const f of readdirSync(dest)) if (f.endsWith('.md') && !pages.has(f)) rmSync(join(dest, f));
  for (const [f, text] of pages) writeFileSync(join(dest, f), text);
}
