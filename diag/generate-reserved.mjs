// Write provenance/reserved-words.tsv from IBM's "Reserved words" appendix: each word with the
// column IBM marks it in, Reserved, Standard only or Potential reserved words. ironwork vendors the
// file and refuses a Reserved word used as a user-defined name, as Enterprise COBOL does.
//
// Usage: curl -sS -L -A curl/8.7.1 '<URL>' -o appendix.html   (IBM Docs answers other agents 403)
//        node diag/generate-reserved.mjs appendix.html [destTsv]
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const URL_ = 'https://www.ibm.com/docs/en/cobol-zos/6.4?topic=appendixes-reserved-words';
const HEADER = ['Word', 'Reserved', 'Standard only', 'Potential reserved words'];
const CATEGORY = ['reserved', 'standard-only', 'potential'];

const [page, dest = fileURLToPath(new URL('../provenance/reserved-words.tsv', import.meta.url))] = process.argv.slice(2);
if (!page) throw new Error('usage: node diag/generate-reserved.mjs appendix.html [destTsv]');
const bytes = readFileSync(page);
const html = bytes.toString('utf8');

const tables = html.match(/<table[^>]*class="defaultstyle"[^>]*>[\s\S]*?<\/table>/g) || [];
if (tables.length !== 1) throw new Error(`expected one defaultstyle table, found ${tables.length}`);
const text = (cell) => cell.replace(/<[^>]+>/g, '')
  .replace(/&nbsp;|&#160;/g, ' ').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&')
  .replace(/ /g, ' ').replace(/\s+/g, ' ').trim();
const rows = (tables[0].match(/<tr[\s\S]*?<\/tr>/g) || []).map((tr) => [...tr.matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/g)].map((m) => text(m[1])));
if (JSON.stringify(rows[0]) !== JSON.stringify(HEADER)) throw new Error(`the table's header is ${JSON.stringify(rows[0])}`);

const words = [];
for (const row of rows.slice(1)) {
  if (row.length !== 4) throw new Error(`a row has ${row.length} cells: ${JSON.stringify(row)}`);
  // The operator rows hold a symbol and a gloss, not a word; they are reserved characters.
  if (!/^[A-Z][A-Z0-9-]*$/.test(row[0])) continue;
  const marked = row.slice(1).map((c) => c === 'X');
  if (marked.filter(Boolean).length !== 1) throw new Error(`${row[0]} is marked in ${marked.filter(Boolean).length} columns`);
  words.push([row[0], CATEGORY[marked.indexOf(true)]]);
}

const sha256 = createHash('sha256').update(bytes).digest('hex');
const counts = CATEGORY.map((c) => `${words.filter((w) => w[1] === c).length} ${c}`).join(', ');
writeFileSync(dest, [
  `# The words IBM Enterprise COBOL for z/OS 6.4 lists in its Language Reference appendix "Reserved words" (${URL_}), each with the column it is marked in: ${counts}.`,
  '# Only a reserved word is refused as a user-defined name: a standard-only word is reserved by the COBOL standard and not by Enterprise COBOL, and a potential one may be in a later release.',
  `# GENERATED by diag/generate-reserved.mjs from the appendix page (${bytes.length} bytes, sha256 ${sha256}); ironwork vendors this file.`,
  '# word\tcategory',
  ...words.map((w) => w.join('\t')),
].join('\n') + '\n', 'utf8');
console.log(`wrote ${dest}: ${words.length} words (${counts})`);
