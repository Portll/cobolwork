// Write test/fixtures/evidence/kinds.tsv from lib/evidence/record.mjs: each record kind, the file it
// belongs in, the fields it may carry and those it must. ironwork vendors the table and holds the
// records its run journal writes to it, so neither tool writes a record the other's verifier refuses.
// Write test/fixtures/evidence/sinks.tsv from lib/dataflow.mjs: the sink kinds a sink record may name,
// which ironwork holds the sinks it raises to, so that each one joins a finding.
//
// Usage: node generate-evidence-kinds.mjs <destDir>
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { JOURNAL_KINDS, KINDS, LEDGER_KINDS } from '../lib/evidence/record.mjs';
import { SINK_KINDS } from '../lib/dataflow.mjs';

const [dest] = process.argv.slice(2);
if (!dest) { console.error('usage: generate-evidence-kinds.mjs <destDir>'); process.exit(2); }

const rows = Object.entries(KINDS).map(([kind, spec]) => {
  const file = JOURNAL_KINDS.has(kind) ? 'journal' : LEDGER_KINDS.has(kind) ? 'ledger' : null;
  if (!file) { console.error(`${kind} is in neither JOURNAL_KINDS nor LEDGER_KINDS`); process.exit(3); }
  return [kind, file, Object.keys(spec.fields).join(' '), spec.required.join(' ')].join('\t');
});

const table = (source, header, lines) => [`# Generated by diag/generate-evidence-kinds.mjs from ${source}; do not edit.`, header, ...lines, ''].join('\n');
writeFileSync(join(dest, 'kinds.tsv'), table('lib/evidence/record.mjs', '# kind\tfile\tfields\trequired', rows));
writeFileSync(join(dest, 'sinks.tsv'), table('lib/dataflow.mjs', '# sink', Object.keys(SINK_KINDS).sort()));
